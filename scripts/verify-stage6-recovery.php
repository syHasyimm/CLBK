<?php

use App\Services\BackupService;
use Illuminate\Contracts\Console\Kernel;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;

// Restore drill on synthetic data only. Both source and destination must be in a stage6 workspace.
$root = dirname(__DIR__);
$contextFile = realpath($argv[1] ?? '');
$cache = realpath($root.'/.cache');
if (! $contextFile || ! $cache || basename($contextFile) !== 'context.json'
    || ! str_starts_with(str_replace('\\', '/', $contextFile), str_replace('\\', '/', $cache).'/stage6-')) {
    throw new RuntimeException('Pass a context.json generated by prepare-stage6-acceptance.php.');
}
$directory = dirname($contextFile);
$context = json_decode(file_get_contents($contextFile), true, flags: JSON_THROW_ON_ERROR);
$environment = $context['environment'];
if (realpath($environment['DB_DATABASE']) !== realpath($directory.'/database.sqlite')
    || $environment['BACKUP_PATH'] !== $directory.'/backups'
    && str_replace('\\', '/', $environment['BACKUP_PATH']) !== str_replace('\\', '/', $directory).'/backups') {
    throw new RuntimeException('Context paths must stay within the isolated workspace.');
}
foreach ($environment as $key => $value) {
    putenv($key.'='.$value);
    $_ENV[$key] = $value;
    $_SERVER[$key] = $value;
}
require $root.'/vendor/autoload.php';
$app = require $root.'/bootstrap/app.php';
$app->make(Kernel::class)->bootstrap();
if (realpath(DB::connection()->getDatabaseName()) !== realpath($directory.'/database.sqlite')) {
    throw new RuntimeException('Isolated database configuration failed.');
}
config(['app.maintenance.driver' => 'cache', 'app.maintenance.store' => 'array', 'session.driver' => 'database']);
$service = app(BackupService::class);
$backup = $service->create(reason: 'restore-drill');
$archive = $service->path($backup['id']);
$manifest = $service->verify($archive);
$replacement = $directory.'/replacement-'.bin2hex(random_bytes(4));
mkdir($replacement, 0700);
$started = microtime(true);
DB::purge();
config(['database.connections.sqlite.database' => $replacement.'/database.sqlite',
    'filesystems.disks.local.root' => $replacement.'/proofs']);
Storage::forgetDisk('local');
$app->maintenanceMode()->activate(['time' => time()]);
$result = $service->restore($archive, true);
$proofsMatch = true;
foreach ($result['state']['proofs'] as $proof) {
    $path = Storage::disk('local')->path($proof['storage_path']);
    $proofsMatch = $proofsMatch && hash_file('sha256', $path) === $manifest['entries']['proofs/'.$proof['storage_path']]['sha256'];
}
$seconds = round(microtime(true) - $started, 3);
$report = ['recorded_at' => gmdate('c'), 'environment' => PHP_OS_FAMILY.' PHP '.PHP_VERSION,
    'scope' => 'Isolated synthetic dataset; restore begins after replacement runtime is available.',
    'archive_id' => $backup['id'], 'archive_sha256' => hash_file('sha256', $archive), 'archive_bytes' => filesize($archive),
    'duration_seconds' => $seconds, 'within_two_hours' => $seconds <= 7200,
    'business_state_matches' => $backup['state'] === $result['state'], 'proof_checksums_match' => $proofsMatch,
    'business_table_count' => count($result['state']['tables']), 'tables' => $result['state']['tables'],
    'metrics' => $result['state']['metrics'], 'proof_count' => count($result['state']['proofs']),
    'sessions_revoked' => DB::table('sessions')->count() === 0,
    'remember_tokens_revoked' => DB::table('users')->whereNotNull('remember_token')->count() === 0,
    'maintenance_remains_active' => $app->isDownForMaintenance()];
$json = json_encode($report, JSON_PRETTY_PRINT | JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES);
file_put_contents($directory.'/recovery-report.json', $json.PHP_EOL);
echo $json.PHP_EOL;
if (! $report['business_state_matches'] || ! $proofsMatch || ! $report['within_two_hours']) {
    exit(1);
}
